// Devuelve true mientras al menos un pixel del cursor siga tocando la
// linea blanca. La OLED es monocromatica, por eso el cursor se distingue
// por ser un cuadrado de 3x3, mas grueso que el camino.
bool cursorSobreLinea(const unsigned char* bmp, int cx, int cy, int radio) {
  for (int dy = -radio; dy <= radio; dy++)
    for (int dx = -radio; dx <= radio; dx++)
      if (pixelEnBitmap(bmp, cx + dx, cy + dy))
        return true;

  return false;
}

// ============================================================
//  TRAZA FACIL (seguidor de linea)
//  - El camino es una linea BLANCA sobre fondo NEGRO
//  - El cursor inicia en el extremo inferior izquierdo
//  - Gana al llegar al extremo inferior derecho
//  - Pierde solo cuando el cursor queda completamente fuera de la linea
// ============================================================
void iniciarTrazaFacil()
{
    // Centros reales de los puntos verde y rojo de la imagen de referencia.
    // Con radio 1, el cursor inicial en (2, 61) toca la linea de x=3..4.
    constexpr int START_X = 2;
    constexpr int START_Y = 61;

    constexpr int META_X = 125;
    constexpr int META_Y = 59;

    constexpr float VEL = 1.2f;
    constexpr int ZONA_MUERTA = 600;
    constexpr int RADIO_META = 8;
    constexpr int RADIO_CURSOR = 1;

    // Mostrar el cursor desde el primer instante en el punto de inicio.
    dibujarJuegoNavegacion(epd_bitmap_Traza_Facil, START_X, START_Y, 1);
    delay(800);

    float cx = START_X;
    float cy = START_Y;
    unsigned long tInicioJuego = millis();

    unsigned long tFrame = 0;

    while (true)
    {
        if (!digitalRead(JOY_SW))
        {
            delay(300);
            enviarMetricaJuego("trazaFacil", millis() - tInicioJuego, "perdio");
            return;
        }

        if (millis() - tFrame < 33)
            continue;

        tFrame = millis();

        int rawH = analogRead(JOY_HOR);
        int rawV = analogRead(JOY_VER);

        float dx = abs(rawH - 2048) > ZONA_MUERTA ?
                   (rawH - 2048) / 2048.0f * VEL : 0;

        float dy = abs(rawV - 2048) > ZONA_MUERTA ?
                   (rawV - 2048) / 2048.0f * VEL : 0;

        int ix = constrain(cx + dx, 1, 126);
        int iy = constrain(cy + dy, 1, 62);

        // Hay tolerancia: pierde unicamente cuando ninguno de los pixeles
        // del cursor 3x3 conserva contacto con el camino.
        if (!cursorSobreLinea(epd_bitmap_Traza_Facil, ix, iy, RADIO_CURSOR))
        {
            dibujarJuegoNavegacion(epd_bitmap_Traza_Facil, ix, iy, 1);
            animacionGameOverNav();
            enviarMetricaJuego("trazaFacil", millis() - tInicioJuego, "perdio");
            return;
        }

        cx = ix;
        cy = iy;

        if (abs(ix - META_X) + abs(iy - META_Y) <= RADIO_META)
        {
            dibujarJuegoNavegacion(epd_bitmap_Traza_Facil, ix, iy, 1);
            animacionVictoriaNav();
            enviarMetricaJuego("trazaFacil", millis() - tInicioJuego, "gano");
            return;
        }

        dibujarJuegoNavegacion(epd_bitmap_Traza_Facil, ix, iy, 1);
    }
}

// ============================================================
//  RESCATE
//  - Fondo negro con obstaculos BLANCOS (circulos)
//  - El cursor inicia en el extremo izquierdo (x ~ 2, y ~ 32)
//  - Gana cuando llega al extremo derecho (x >= 118)
//  - Pierde si toca cualquier pixel BLANCO (obstaculo)
// ============================================================
void iniciarRescate() {
  // Mostrar el campo al inicio
  display.clearDisplay();
  display.drawBitmap(0, 0, epd_bitmap_Rescate, 128, 64, 1);
  display.display();
  delay(800);

  // Punto de inicio: extremo izquierdo, centro vertical
  // Buscamos el primer pixel negro en la columna x=2, cerca de y=32
  int startX = 2, startY = 32;
  for (int y = 32; y < 64; y++) {
    if (!pixelEnBitmap(epd_bitmap_Rescate, 2, y)) {
      startY = y;
      goto inicio_rescate_ok;
    }
  }
  for (int y = 31; y >= 0; y--) {
    if (!pixelEnBitmap(epd_bitmap_Rescate, 2, y)) {
      startY = y;
      goto inicio_rescate_ok;
    }
  }
  inicio_rescate_ok:

  float cx = startX;
  float cy = startY;
  unsigned long tInicioJuego = millis();

  // Meta: llegar a x >= 118 (extremo derecho)
  const int   META_X      = 118;
  const float VEL         = 1.4f;
  const int   ZONA_MUERTA = 600;
  unsigned long tFrame    = 0;


  while (true) {
    // Salir con JOY_SW
    if (digitalRead(JOY_SW) == LOW) {
      delay(300);
      enviarMetricaJuego("rescate", millis() - tInicioJuego, "perdio");
      return; }

    // ~30 fps
    unsigned long ahora = millis();
    if (ahora - tFrame < 33) continue;
    tFrame = ahora;

    // Leer joystick
    int rawH = analogRead(JOY_HOR);
    int rawV = analogRead(JOY_VER);
    float dx = 0, dy = 0;
    if (abs(rawH - 2048) > ZONA_MUERTA) dx = (rawH - 2048) / 2048.0f * VEL;
    if (abs(rawV - 2048) > ZONA_MUERTA) dy = (rawV - 2048) / 2048.0f * VEL;

    float nx = constrain(cx + dx, 1, 126);
    float ny = constrain(cy + dy, 1, 62);
    int   ix = (int)nx;
    int   iy = (int)ny;

    // Colision: si toca un pixel BLANCO (obstaculo) = pierde
    // Cursor de 3x3: chequear area completa para ser justo
    bool colision = false;
    for (int dy2 = -1; dy2 <= 1 && !colision; dy2++)
      for (int dx2 = -1; dx2 <= 1 && !colision; dx2++)
        if (pixelEnBitmap(epd_bitmap_Rescate, ix + dx2, iy + dy2))
          colision = true;

    if (colision) {
      dibujarJuegoNavegacion(epd_bitmap_Rescate, (int)cx, (int)cy, 1);
      animacionGameOverNav();
      enviarMetricaJuego("rescate", millis() - tInicioJuego, "perdio");
      return;
    }

    // Mover cursor
    cx = nx;
    cy = ny;

    // Verificar llegada al extremo derecho
    if (ix >= META_X) {
      dibujarJuegoNavegacion(epd_bitmap_Rescate, ix, iy, 1);
      animacionVictoriaNav();
      enviarMetricaJuego("rescate", millis() - tInicioJuego, "gano");
      return;
    }

    dibujarJuegoNavegacion(epd_bitmap_Rescate, ix, iy, 1);
  }
}
