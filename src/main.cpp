// Llena fecha ("21/07/2026") y hora ("13:30") reales.
// Devuelve false si aun no logro sincronizar (usa un timeout corto).
bool obtenerFechaHora(String &fecha, String &hora) {
  struct tm timeinfo;
  if (!getLocalTime(&timeinfo, 5000)) {
    fecha = "00/00/0000";
    hora  = "00:00";
    return false;
  }
  char bufFecha[11];
  strftime(bufFecha, sizeof(bufFecha), "%d/%m/%Y", &timeinfo);
  char bufHora[6];
  strftime(bufHora, sizeof(bufHora), "%H:%M", &timeinfo);
  fecha = String(bufFecha);
  hora  = String(bufHora);
  return true;
}
 
// Convierte milisegundos a formato "1.30 min" (1 min 30 seg)
String formatearDuracion(unsigned long duracionMs) {
  unsigned long totalSegundos = duracionMs / 1000;
  unsigned long minutos  = totalSegundos / 60;
  unsigned long segundos = totalSegundos % 60;
  char buf[12];
  snprintf(buf, sizeof(buf), "%lu.%02lu min", minutos, segundos);
  return String(buf);
}
 
 
// Publica una metrica JSON en arcade/<dispositivoId>/metricas.
void enviarMetricaJuego(const char* juego, unsigned long duracionMs, const String &resultado) {
  String fecha, hora;
  bool horaSincronizada = obtenerFechaHora(fecha, hora);
  String duracionStr = formatearDuracion(duracionMs);

  // ── La carpeta ahora es el nombre del juego, no "partidas" ──
  String carpeta = String(juego);
  carpeta.replace(" ", "");

  int valor = 0;
  bool tieneValor = false;
  for (size_t i = 0; i < resultado.length(); i++) {
    if (isDigit(resultado[i])) {
      tieneValor = true;
      valor = valor * 10 + (resultado[i] - '0');
    }
  }
  String juegoNormalizado = String(juego);
  juegoNormalizado.toLowerCase();
  time_t ahora = 0;
  if (horaSincronizada) time(&ahora);
  secuenciaMensajes++;
  String idMensaje = String(MQTT_DEVICE_ID) + "-" +
                     String((unsigned long)ahora) + "-" +
                     String(secuenciaMensajes);

  JsonDocument metrica;
  metrica["idMensaje"] = idMensaje;
  metrica["dispositivoId"] = MQTT_DEVICE_ID;
  metrica["juego"] = carpeta;
  metrica["duracion"] = duracionStr;
  metrica["duracionMs"] = duracionMs;
  metrica["resultado"] = resultado;
  metrica["fecha"] = fecha;
  metrica["hora"] = hora;
  if (horaSincronizada) metrica["timestamp"] = (unsigned long)ahora;
  if (tieneValor && juegoNormalizado.indexOf("simon") >= 0)
    metrica["puntaje"] = valor;
  if (tieneValor && juegoNormalizado.indexOf("pinta") >= 0)
    metrica["nivel"] = valor;

  String payload;
  serializeJson(metrica, payload);
  String topic = "arcade/" + String(MQTT_DEVICE_ID) + "/metricas";

  if (!conectarMQTT()) {
    Serial.println("Metrica NO publicada: broker MQTT no disponible.");
    return;
  }

  bool publicada = mqttClient.publish(topic.c_str(), payload.c_str(), false);
  mqttClient.loop();
  Serial.printf("MQTT %s -> %s\n", publicada ? "publicado" : "fallo", topic.c_str());
  if (!publicada) Serial.println(payload);
}




