// Se ejecuta una sola vez por encendido, despues de conectarse al WiFi.
void animacionInicioArcade() {
  if (!menuRecienIniciado || WiFi.status() != WL_CONNECTED) return;

  // Se escriben los cinco pines de forma explicita para que la prueba de
  // encendido tambien valide los LED rojo y verde.
  const uint8_t ledsInicio[5] = {
    LED_ROJO, LED_VERDE, LED_AMARILLO, LED_AZUL, LED_NARANJA
  };

  for (int i = 0; i < 5; i++) {
    pinMode(ledsInicio[i], OUTPUT);
    digitalWrite(ledsInicio[i], LOW);
  }

  // Prueba corta individual: permite comprobar visualmente cada color.
  for (int i = 0; i < 5; i++) {
    digitalWrite(ledsInicio[i], HIGH);
    tone(BUZZER_PIN, 900 + (i * 180));
    delay(160);
    digitalWrite(ledsInicio[i], LOW);
  }

  // Confirmacion final: todos los LED encendidos al mismo tiempo.
  for (int i = 0; i < 5; i++) {
    digitalWrite(ledsInicio[i], HIGH);
  }
  tone(BUZZER_PIN, 1500);

  delay(800);

  noTone(BUZZER_PIN);
  for (int i = 0; i < 5; i++) {
    digitalWrite(ledsInicio[i], LOW);
  }
  menuRecienIniciado = false;
}




// MQTT: el ESP32 solo publica metricas. El backend es el unico componente
// autorizado para escribir en Firebase.
WiFiClientSecure mqttTlsClient;
PubSubClient mqttClient(mqttTlsClient);
unsigned long secuenciaMensajes = 0;

void inicializarMQTT() {
  mqttClient.setServer(MQTT_HOST, MQTT_PORT);
  mqttClient.setBufferSize(1024);
  mqttClient.setKeepAlive(30);
  mqttClient.setSocketTimeout(8);

  if (strlen(MQTT_ROOT_CA) > 0) {
    mqttTlsClient.setCACert(MQTT_ROOT_CA);
  } else {
    mqttTlsClient.setInsecure();
    Serial.println("ADVERTENCIA: MQTT TLS sin validacion de certificado.");
  }
}

bool conectarMQTT() {
  if (mqttClient.connected()) return true;
  if (WiFi.status() != WL_CONNECTED) {
    Serial.println("Sin WiFi -> no se puede conectar al broker MQTT.");
    return false;
  }

  String clientId = String(MQTT_DEVICE_ID) + "-" +
                    String((uint32_t)(ESP.getEfuseMac() & 0xFFFFFFFF), HEX);

  for (int intento = 1; intento <= 3; intento++) {
    Serial.printf("Conectando a HiveMQ (%d/3)...\n", intento);
    if (mqttClient.connect(clientId.c_str(), MQTT_USERNAME, MQTT_PASSWORD)) {
      Serial.println("MQTT conectado.");
      return true;
    }
    Serial.printf("MQTT fallo, estado=%d\n", mqttClient.state());
    delay(750);
  }
  return false;
}





